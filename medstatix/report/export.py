def results_to_html(results: list[Result]) -> str:
    cnt = {"t": 0, "f": 0}
    body = "\n".join(r.to_html(counters=cnt) for r in results)
    return (f"<!DOCTYPE html><html><head><meta charset='utf-8'><title>{APP_NAME} report</title>"
            f"<style>{HTML_CSS}</style></head><body>{body}"
            f"<p class='note'>Generated by {APP_NAME} {APP_VERSION}</p></body></html>")


def _set_cell_border(cell, **kwargs):
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    tcPr = cell._tc.get_or_add_tcPr()
    borders = tcPr.first_child_found_in("w:tcBorders")
    if borders is None:
        borders = OxmlElement("w:tcBorders")
        tcPr.append(borders)
    for edge, val in kwargs.items():
        el = OxmlElement(f"w:{edge}")
        for k, v in val.items():
            el.set(qn(f"w:{k}"), str(v))
        borders.append(el)


def results_to_docx(results: list[Result], path: str, include_methods=True):
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Pt, Mm, RGBColor
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(11)
    sec = doc.sections[0]
    sec.left_margin = sec.right_margin = Mm(20)
    thick = {"sz": 12, "val": "single", "color": "000000"}
    thin = {"sz": 6, "val": "single", "color": "000000"}
    none = {"val": "nil"}
    tcount = fcount = 0
    for res in results:
        doc.add_heading(res.title.replace("🧠 ", ""), level=1)
        if res.subtitle:
            p = doc.add_paragraph(res.subtitle)
            p.runs[0].italic = True
        for b in res.blocks:
            if b.kind == "heading":
                doc.add_heading(b.content, level=2)
            elif b.kind in ("text", "note"):
                doc.add_paragraph(b.content)
            elif b.kind == "warning":
                p = doc.add_paragraph("⚠ " + b.content)
                p.runs[0].font.color.rgb = RGBColor(0xB0, 0x60, 0x00)
            elif b.kind == "interpret":
                il = getattr(SETTINGS, "interp_lang", "same")
                langs = [SETTINGS.language] if il == "same" else (["en", "ar"] if il == "both" else [il])
                for lg in langs:
                    txt = b.content.get(lg) or b.content["en"]
                    p = doc.add_paragraph()
                    r = p.add_run("Interpretation: " if lg == "en" else "التفسير: ")
                    r.bold = True
                    p.add_run(txt)
                    if lg == "ar":
                        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
                        from docx.oxml import OxmlElement
                        from docx.oxml.ns import qn
                        p._p.get_or_add_pPr().append(OxmlElement("w:bidi"))
                        for run in p.runs:
                            rpr = run._r.get_or_add_rPr(); rtl = OxmlElement("w:rtl"); rpr.append(rtl)
            elif b.kind == "methods" and include_methods:
                p = doc.add_paragraph()
                p.add_run("Methods/Results text: ").bold = True
                p.add_run(b.content)
            elif b.kind == "table":
                tcount += 1
                df = Result.format_df(b.content, b.p_columns)
                show_index = not isinstance(df.index, pd.RangeIndex)
                if show_index:
                    df = df.reset_index()
                cap = doc.add_paragraph()
                cap.add_run(f"Table {tcount}").bold = True
                doc.add_paragraph().add_run(b.caption or "").italic = True
                t = doc.add_table(rows=len(df) + 1, cols=len(df.columns))
                for j, c in enumerate(df.columns):
                    cell = t.cell(0, j)
                    cell.text = str(c)
                    cell.paragraphs[0].runs[0].bold = True
                    _set_cell_border(cell, top=thick, bottom=thin, left=none, right=none)
                for i in range(len(df)):
                    for j in range(len(df.columns)):
                        cell = t.cell(i + 1, j)
                        cell.text = str(df.iat[i, j])
                        _set_cell_border(cell, top=none, left=none, right=none,
                                         bottom=thick if i == len(df) - 1 else none)
                for row in t.rows:
                    for j, cell in enumerate(row.cells):
                        for par in cell.paragraphs:
                            par.alignment = WD_ALIGN_PARAGRAPH.LEFT if j == 0 else WD_ALIGN_PARAGRAPH.CENTER
                            for run in par.runs:
                                run.font.size = Pt(9.5)
                if b.note:
                    p = doc.add_paragraph()
                    p.add_run("Note. ").italic = True
                    p.add_run(b.note).font.size = Pt(9)
            elif b.kind == "figure":
                fcount += 1
                png = fig_to_png_bytes(b.content, dpi=300)
                doc.add_picture(io.BytesIO(png), width=Mm(150))
                p = doc.add_paragraph()
                p.add_run(f"Figure {fcount}. ").bold = True
                p.add_run(b.caption)
        doc.add_paragraph()
    p = doc.add_paragraph(f"Analyses performed with {APP_NAME} {APP_VERSION}.")
    p.runs[0].font.size = Pt(8)
    doc.save(path)


def results_to_xlsx(results: list[Result], path: str):
    used = set()
    with pd.ExcelWriter(path, engine="openpyxl") as xw:
        for ri, res in enumerate(results):
            for ti, b in enumerate(res.tables):
                name = re.sub(r"[\[\]:*?/\\]", "", f"{ri+1}.{ti+1} {b.caption or res.title}")[:31]
                while name in used:
                    name = name[:28] + f"_{len(used)}"
                used.add(name)
                df = b.content
                df.to_excel(xw, sheet_name=name, index=not isinstance(df.index, pd.RangeIndex))
                ws = xw.sheets[name]
                for col in ws.columns:
                    width = max(len(str(c.value or "")) for c in col) + 2
                    ws.column_dimensions[col[0].column_letter].width = min(width, 45)


def export_figure(fig, path: str, dpi: int | None = None, width_mm=None, height_mm=None):
    """Save a figure in PNG / TIFF (LZW) / SVG / PDF / EPS at the requested resolution."""
    dpi = dpi or SETTINGS.export_dpi
    ext = os.path.splitext(path)[1].lower()
    old = fig.get_size_inches().copy()
    if width_mm and height_mm:
        fig.set_size_inches(width_mm / 25.4, height_mm / 25.4)
    kw = dict(dpi=dpi, bbox_inches="tight")
    if ext in (".tif", ".tiff"):
        kw["pil_kwargs"] = {"compression": "tiff_lzw"}
    if ext in (".jpg", ".jpeg"):
        kw["pil_kwargs"] = {"quality": 97, "subsampling": 0}
        kw["facecolor"] = "white"
    fig.savefig(path, **kw)
    fig.set_size_inches(*old)
